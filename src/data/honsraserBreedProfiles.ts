// 25 rasprofiler för /honsraser/:slug-sidorna.
// Skrivet i jag-form av en hobbyhönsägare med ~10 års erfarenhet.
// Tonen ska matcha existerande honsraserContent.ts – ärlig, konkret,
// inga uppfunna siffror. Riktvärden på värpning och vikt är vedertagna.

import type { LongformPage, ContentSection } from './honsraserContent';

export interface BreedProfile {
  slug: string;                 // /honsraser/<slug>
  namn: string;
  ursprung: string;
  vikt: string;                 // t.ex. "2,5–3,5 kg"
  aggPerAr: string;             // t.ex. "~180"
  aggfarg: string;              // t.ex. "Beige"
  temperament: string;
  vinter: string;               // Vinterhärdighet i svenskt klimat
  ljudniva: string;             // Låg/Måttlig/Hög + kort not
  nyborjarvanlig: string;       // Låg/Medel/Hög + kort not
  passar: string;               // Vem/vilken situation
  description: string;          // ≤160 tecken, unik
  intro: [string, string];      // 2 stycken, tillsammans ≥150 ord
  faq: [string, string][];      // exakt 4
  related: string[];            // 4 slugs (från listan nedan eller existerande)
  swedishHeritage?: boolean;    // svensk lantras → SLK/genbank
  h1Suffix?: string;            // valfri egen h1-svans
}

// Etikett för länkar mellan raser (används i relatedLinks)
export function breedLabel(slug: string): string {
  const p = BREED_PROFILES.find((b) => b.slug === slug);
  if (p) return p.namn;
  // Fallback för de befintliga (icke-ras) landningarna
  const fallback: Record<string, string> = {
    'skansk-blommehona': 'Skånsk blommehöna',
    'dvarghons': 'Dvärghöns',
    'honsraser': 'Hönsraser – översikt',
    'honsraser-lista': 'Hönsraser A–Ö',
  };
  return fallback[slug] ?? slug;
}

const SLK_NOTE =
  'Detta är en svensk lantras som bevaras av Svenska Lanthönsklubben (SLK) och finns i deras genbank. Väljer du en stamboksförd individ från en SLK-ansluten uppfödare bidrar dina kycklingar till att bredda den genetiska basen och hålla rasen vid liv för kommande generationer.';

export function buildBreedPage(b: BreedProfile): LongformPage {
  const sections: ContentSection[] = [
    {
      heading: `Snabbfakta om ${b.namn}`,
      paragraphs: [
        `Här är kortversionen jag själv hade velat ha när jag valde ras. Alla siffror är riktvärden för hobbyflockar under värpsäsong – inte garantier.`,
      ],
      bullets: [
        `Ursprung: ${b.ursprung}`,
        `Värpning: ${b.aggPerAr} ägg per år`,
        `Äggfärg: ${b.aggfarg}`,
        `Vikt: ${b.vikt}`,
        `Temperament: ${b.temperament}`,
        `Vinterhärdighet i svenskt klimat: ${b.vinter}`,
        `Ljudnivå: ${b.ljudniva}`,
        `Nybörjarvänlighet: ${b.nyborjarvanlig}`,
      ],
    },
    ...(b.swedishHeritage
      ? [{ heading: 'Svensk lantras och genbank', paragraphs: [SLK_NOTE] } as ContentSection]
      : []),
    {
      heading: `Passar ${b.namn} dig?`,
      paragraphs: [
        `${b.namn} passar särskilt bra för: ${b.passar}. Det betyder inte att rasen bara duger där – men det är i den situationen den kommer mest till sin rätt. Är du osäker rekommenderar jag att läsa nybörjarguiden och titta i hönskalendern för hur skötselåret ser ut innan du bestämmer dig.`,
      ],
    },
  ];

  const relatedLinks = [
    ...b.related.map((s) => ({ href: `/honsraser/${s}`, label: breedLabel(s) })),
    { href: '/borja-med-hons', label: 'Börja med höns – nybörjarguide' },
    { href: '/honskalender', label: 'Hönskalender och rutiner året runt' },
  ];

  return {
    slug: b.slug,
    path: `/honsraser/${b.slug}`,
    title: `${b.namn} – värpning, temperament & skötsel | Hönsgården`,
    description: b.description,
    h1: b.h1Suffix ? `${b.namn} – ${b.h1Suffix}` : `${b.namn} – värpning, temperament och skötsel`,
    eyebrow: b.swedishHeritage ? 'Svensk lantras' : 'Hönsras',
    intro: [...b.intro],
    toc: [
      'Snabbfakta',
      ...(b.swedishHeritage ? ['Svensk lantras & genbank'] : []),
      'Passar rasen dig?',
      'Vanliga frågor',
    ],
    sections,
    faq: b.faq.map(([q, a]) => ({ q, a })),
    relatedLinks,
    breedName: b.namn,
  };
}

